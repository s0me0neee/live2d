// Scans the Live2D model directory for *.exp3.json expression files and
// generates src/expressions/generated.ts, assigning each a keybind.
// Node port of the old src-tauri/src/build_exp_keys.rs.
//
//   Regenerate after adding/renaming expressions:  node scripts/build-exp-keys.mjs
import { readdir, mkdir, writeFile } from "node:fs/promises";
import { dirname } from "node:path";

const MODEL_DIR = "model/ariu/";
const OUT_PATH = "src/expressions/generated.ts";
const EXP_SUFFIX = ".exp3.json";
// Keys assigned to expressions in sorted order. Add more if you have >10.
const KEYS = ["1", "2", "3", "4", "5", "6", "7", "8", "9", "0"];

const files = (await readdir(MODEL_DIR))
	.filter((name) => name.endsWith(EXP_SUFFIX))
	.sort();

let out = "";
out += "// AUTO-GENERATED by scripts/build-exp-keys.mjs — do not edit by hand.\n";
out += "// Regenerate: node scripts/build-exp-keys.mjs\n\n";
out += "export interface ExpressionBinding {\n";
out += "\tname: string;\n";
out += "\tfile: string;\n";
out += "\tkey: string; // keyboard shortcut to toggle this expression\n";
out += "}\n\n";
out += "export const expressions: ExpressionBinding[] = [\n";
for (let i = 0; i < files.length; i++) {
	const file = files[i];
	const name = file.slice(0, -EXP_SUFFIX.length);
	const key = KEYS[i] ?? "";
	out += `{ name: ${JSON.stringify(name)}, file: ${JSON.stringify(file)}, key: ${JSON.stringify(key)} },\n`;
}
out += "];\n";

await mkdir(dirname(OUT_PATH), { recursive: true });
await writeFile(OUT_PATH, out);
console.log(`wrote ${files.length} expressions -> ${OUT_PATH}`);
